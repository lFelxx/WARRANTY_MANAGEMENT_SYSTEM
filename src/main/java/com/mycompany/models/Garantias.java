

package com.mycompany.models;


public class Garantias {
    private String id_garantia;
    private String factura;
    private String price;
    private String userCed;
    private String userName;
    private String apellido;
    private String telefono;
    private String damag;

    public String getId_garantia() {
        return id_garantia;
    }

    public void setId_garantia(String id_garantia) {
        this.id_garantia = id_garantia;
    }

    public String getFactura() {
        return factura;
    }

    public void setFactura(String factura) {
        this.factura = factura;
    }

    public String getPrice() {
        return price;
    }

    public void setPrice(String price) {
        this.price = price;
    }

    public String getUserCed() {
        return userCed;
    }

    public void setUserCed(String userCed) {
        this.userCed = userCed;
    }

    public String getUserName() {
        return userName;
    }

    public void setUserName(String userName) {
        this.userName = userName;
    }

    public String getApellido() {
        return apellido;
    }

    public void setApellido(String apellido) {
        this.apellido = apellido;
    }

    public String getTelefono() {
        return telefono;
    }

    public void setTelefono(String telefono) {
        this.telefono = telefono;
    }

    public String getDamag() {
        return damag;
    }

    public void setDamag(String damag) {
        this.damag = damag;
    }


    

}
